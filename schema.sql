drop policy if exists "Visitors record visits" on public.page_visits;
create policy "Visitors record visits" on public.page_visits for insert to anon, authenticated
  with check (session_id ~ '^[0-9a-fA-F-]{20,100}$');
drop policy if exists "Only admin reads visits" on public.page_visits;
